--------------------------------------------------------------------------------
-- Vimオプション設定
-- ショートハンドを使わず、正式名称で記述して可読性を確保
--------------------------------------------------------------------------------

local opt = vim.opt

--------------------------------------------------------------------------------
-- 表示設定
--------------------------------------------------------------------------------
opt.number = true           -- 行番号を表示
opt.ruler = true            -- カーソル位置を表示
opt.showmatch = true        -- 対応する括弧をハイライト
opt.termguicolors = true    -- 24bitカラーを有効化
opt.signcolumn = 'yes'      -- サイン列を常に表示（LSPエラー等）
opt.cmdheight = 0           -- コマンドラインの高さ（0で非表示）
opt.laststatus = 0          -- ステータスラインを非表示

--------------------------------------------------------------------------------
-- 編集設定
--------------------------------------------------------------------------------
opt.hidden = true           -- バッファを保存せずに切り替え可能
opt.expandtab = true        -- タブをスペースに展開
opt.smartindent = true      -- スマートインデント
opt.tabstop = 2             -- タブ幅
opt.shiftwidth = 2          -- インデント幅

--------------------------------------------------------------------------------
-- 検索設定
--------------------------------------------------------------------------------
opt.hlsearch = true         -- 検索結果をハイライト
opt.incsearch = true        -- インクリメンタルサーチ
opt.ignorecase = true       -- 大文字小文字を無視
opt.smartcase = true        -- 大文字が含まれる場合は区別
opt.infercase = true        -- 補完時の大文字小文字を推測

--------------------------------------------------------------------------------
-- システム設定
--------------------------------------------------------------------------------
opt.encoding = 'utf-8'      -- 文字エンコーディング
opt.virtualedit = 'block'   -- 矩形選択時に文字がなくても移動可能
opt.clipboard = 'unnamedplus' -- システムクリップボードを使用
opt.completeopt = 'noselect'  -- 補完メニューの動作

--------------------------------------------------------------------------------
-- 環境設定
--------------------------------------------------------------------------------
vim.env.LANG = 'C'          -- 言語設定（英語メッセージ）
